/**
 * ISO 3166-1 alpha-2 country codes for the property form's country combobox.
 *
 * `property.address.country` stores (and the contract validates) the 2-letter
 * code — see `packages/contract/src/property.ts`. The field used to just BE a
 * 2-character text input, so a landlord had to already know that Nepal is `NP`.
 * This keeps the stored value exactly the same 2-letter code; it only changes
 * what the person has to type to find it — same shape as `timezones.ts`.
 *
 * Unlike `Intl.supportedValuesOf('timeZone')`, there is no equivalent runtime
 * enumeration for country codes — `Intl.supportedValuesOf` only covers
 * `calendar`, `collation`, `currency`, `numberingSystem`, `timeZone` and `unit`,
 * not regions. So the codes themselves are a short, stable, hand-kept list (ISO
 * 3166-1 barely changes), and `Intl.DisplayNames` supplies the English name for
 * each one at runtime rather than hand-typing ~249 of them.
 */

